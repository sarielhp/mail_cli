var (
	graphicCacheLock sync.RWMutex
	graphicCache     = make(map[string]string)
)

func getCacheKey(data []byte, width, height int, invert bool) string {
	sum := sha256.Sum256(data)
	return fmt.Sprintf("%x_%d_%d_%t", sum[:8], width, height, invert)
}

func isImageAttachment(att email.Attachment) bool {
	ext := strings.ToLower(filepath.Ext(att.Filename))
	ct := strings.ToLower(att.ContentType)
	switch ext {
	case ".png", ".jpg", ".jpeg", ".jpe", ".jfif", ".gif", ".webp", ".bmp", ".tiff", ".tif", ".ico", ".svg", ".avif", ".heic", ".heif":
		return true
	}
	if strings.HasPrefix(ct, "image/") {
		return true
	}
	if len(att.Data) >= 8 {
		if bytes.HasPrefix(att.Data, []byte{0x89, 'P', 'N', 'G', '\r', '\n', 0x1a, '\n'}) {
			return true
		}
		if bytes.HasPrefix(att.Data, []byte{0xff, 0xd8, 0xff}) {
			return true
		}
		if bytes.HasPrefix(att.Data, []byte("GIF87a")) || bytes.HasPrefix(att.Data, []byte("GIF89a")) {
			return true
		}
		if len(att.Data) >= 12 && bytes.HasPrefix(att.Data, []byte("RIFF")) && bytes.Equal(att.Data[8:12], []byte("WEBP")) {
			return true
		}
		if bytes.HasPrefix(att.Data, []byte{'B', 'M'}) {
			return true
		}
	}
	return false
}

func renderGraphicAttachmentPreview(att email.Attachment, width int, height int, invert bool) (string, error) {
	if len(att.Data) == 0 {
		return "", fmt.Errorf("empty attachment data")
	}

	key := getCacheKey(att.Data, width, height, invert)
	graphicCacheLock.RLock()
	if cached, ok := graphicCache[key]; ok {
		graphicCacheLock.RUnlock()
		return cached, nil
	}
	graphicCacheLock.RUnlock()

	tmpDir, err := os.MkdirTemp("", cfg_g.AppName+"_graphic_*")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(tmpDir)

	var imagePath string
	isPDF := isPDFAttachment(att)
	switch {
	case isPDF:
		pdfPath := filepath.Join(tmpDir, "doc.pdf")
		if writeErr := os.WriteFile(pdfPath, att.Data, 0600); writeErr != nil {
			return "", writeErr
		}
		prefix := filepath.Join(tmpDir, "page")
		ctxPPM, cancelPPM := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancelPPM()
		cmdPPM := exec.CommandContext(ctxPPM, "pdftoppm", "-png", "-r", "150", "-f", "1", "-l", "1", pdfPath, prefix)
		if runErr := cmdPPM.Run(); runErr != nil {
			return "", runErr
		}
		matches, _ := filepath.Glob(filepath.Join(tmpDir, "page-*.png"))
		if len(matches) == 0 {
			return "", fmt.Errorf("no png generated by pdftoppm")
		}
		imagePath = matches[0]
	case isImageAttachment(att):
		ext := filepath.Ext(att.Filename)
		if ext == "" {
			ext = ".png"
		}
		imagePath = filepath.Join(tmpDir, "image"+ext)
		if writeErr := os.WriteFile(imagePath, att.Data, 0600); writeErr != nil {
			return "", writeErr
		}
	default:
		return "", fmt.Errorf("not a graphical attachment")
	}

	chafaH := height
	if isPDF && chafaH < width*4 {
		chafaH = width * 4
	}

	sizeArg := fmt.Sprintf("%dx%d", max(10, width), max(4, chafaH))
	args := []string{"--format=symbols", "--symbols=vhalf", "--size=" + sizeArg}
	if invert {
		args = append(args, "--invert")
	}
	args = append(args, imagePath)

	ctxChafa, cancelChafa := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancelChafa()
	cmdChafa := exec.CommandContext(ctxChafa, "chafa", args...)
	out, err := cmdChafa.Output()
	if err != nil {
		return "", err
	}
	result := strings.TrimRight(string(out), "\r\n")
	graphicCacheLock.Lock()
	graphicCache[key] = result
	graphicCacheLock.Unlock()
	return result, nil
}

func (m *tuiModel) toggleInvertColors() {
	m.attInvertColors = !m.attInvertColors
	graphicCacheLock.Lock()
	graphicCache = make(map[string]string)
	graphicCacheLock.Unlock()
	m.rightVpAttFilename = ""

	if m.client != nil && m.client.Config() != nil {
		m.client.Config().AttachmentInvertColors = m.attInvertColors
		configPath := m.client.Config().ConfigDir
		if configPath == "" {
			if home, err := os.UserHomeDir(); err == nil {
				configPath = filepath.Join(home, ".config", cfg_g.AppName, "config.json")
			}
		} else if !strings.HasSuffix(configPath, ".json") {
			configPath = filepath.Join(configPath, "config.json")
		}
		if configPath != "" {
			if fc, err := cfg_g.LoadConfigFile(configPath); err == nil && fc != nil {
				fc.AttachmentInvertColors = &m.attInvertColors
				_ = cfg_g.SaveConfigFile(configPath, fc)
			}
		}
	}
	m.detailVpDirty = true
}

func renderICSAttachmentPreview(m *tuiModel, att email.Attachment, width int) string {
	events, err := calendar.ParseAllICSEventsData(att.Data)
	if err != nil || len(events) == 0 {
		return lipgloss.NewStyle().Foreground(lipgloss.Color("#e06c75")).Render("(Failed to parse calendar event: " + att.Filename + ")")
	}

	t := m.theme.Theme()
	labelStyle := lipgloss.NewStyle().Bold(true).Foreground(lipgloss.Color(t.Get(render.ColorHighlightFg)))
	valStyle := lipgloss.NewStyle().Foreground(lipgloss.Color(t.Get(render.ColorFg)))
	secHdrStyle := lipgloss.NewStyle().Bold(true).Foreground(lipgloss.Color("#ffd700"))
	borderStyle := lipgloss.NewStyle().Foreground(lipgloss.Color("#6272a4"))

	var sb strings.Builder
	for idx, ev := range events {
		if idx > 0 {
			sb.WriteString("\n" + borderStyle.Render(strings.Repeat("─", min(width, 60))) + "\n\n")
		}

		summary := ev.Summary
		if summary == "" {
			summary = "(Untitled Event)"
		}

		sb.WriteString(secHdrStyle.Render(fmt.Sprintf("📅 EVENT: %s", email.BidiDisplay(summary))) + "\n\n")
		sb.WriteString(labelStyle.Render("When:        ") + valStyle.Bold(true).Render(formatICSEventTime(ev)) + "\n")

		if ev.RRule != "" {
			recurStyle := lipgloss.NewStyle().Foreground(lipgloss.Color("#79c0ff")).Bold(true)
			sb.WriteString(labelStyle.Render("Repeats:     ") + recurStyle.Render(formatHumanRRule(ev.RRule)) + "\n")
			if nextOccs := formatNextOccurrences(ev, 2); len(nextOccs) > 0 {
				sb.WriteString(labelStyle.Render("Next Sched:  ") + valStyle.Render(strings.Join(nextOccs, " | ")) + "\n")
			}
		}

		switch {
		case ev.ConferenceURL != "":
			joinStyle := lipgloss.NewStyle().Foreground(lipgloss.Color("#50fa7b")).Underline(true)
			sb.WriteString(labelStyle.Render("Join:        ") + joinStyle.Render(ev.ConferenceURL) + "\n")
		case strings.HasPrefix(ev.Location, "http://") || strings.HasPrefix(ev.Location, "https://"):
			joinStyle := lipgloss.NewStyle().Foreground(lipgloss.Color("#50fa7b")).Underline(true)
			sb.WriteString(labelStyle.Render("Join:        ") + joinStyle.Render(ev.Location) + "\n")
		case ev.Location != "":
			sb.WriteString(labelStyle.Render("Location:    ") + valStyle.Render(email.BidiDisplay(ev.Location)) + "\n")
		}

		if ev.Organizer != "" {
			sb.WriteString(labelStyle.Render("Organizer:   ") + valStyle.Render(email.BidiDisplay(ev.Organizer)) + "\n")
		}

		if len(ev.Attendees) > 0 {
			attStr := strings.Join(ev.Attendees, ", ")
			wrapped := email.WrapText(attStr, max(10, width-15))
			sb.WriteString(labelStyle.Render("Attendees:   ") + valStyle.Render(email.BidiDisplay(wrapped)) + "\n")
		}

		if ev.Description != "" {
			sb.WriteString("\n" + labelStyle.Render("Description:") + "\n")
			descLines := strings.Split(ev.Description, "\n")
			for _, dl := range descLines {
				wrapped := email.WrapText(dl, max(10, width-2))
				sb.WriteString(valStyle.Render(wrapped) + "\n")
			}
		}
	}

	return strings.TrimRight(sb.String(), "\n")
}

func renderCodeAttachmentPreview(att email.Attachment, width int) string {
	if len(att.Data) == 0 {
		return "(Empty file)"
	}

	batBin := "batcat"
	if _, err := exec.LookPath("batcat"); err != nil {
		if _, err2 := exec.LookPath("bat"); err2 == nil {
			batBin = "bat"
		} else {
			batBin = ""
		}
	}

	if batBin != "" {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		cmd := exec.CommandContext(ctx, batBin, "--color=always", "--paging=never", fmt.Sprintf("--file-name=%s", att.Filename), fmt.Sprintf("--terminal-width=%d", max(20, width)))
		cmd.Stdin = bytes.NewReader(att.Data)
		out, err := cmd.Output()
		if err == nil && len(out) > 0 {
			return strings.TrimRight(string(out), "\r\n")
		}
	}

	raw := string(att.Data)
	return raw
}

func getPreviewIconAndType(att email.Attachment) (string, string) {
	ext := strings.ToLower(filepath.Ext(att.Filename))
	switch {
	case isPDFAttachment(att):
		return "📕 ", "PDF Document"
	case isImageAttachment(att):
		return "🖼️ ", "Image"
	case email.IsICSAttachment(att):
		return "📅 ", "Calendar Event"
	case ext == ".py":
		return "🐍 ", "Python Source"
	case ext == ".go":
		return "🔷 ", "Go Source"
	case ext == ".rs":
		return "🦀 ", "Rust Source"
	case ext == ".rb":
		return "💎 ", "Ruby Source"
	case ext == ".sh" || ext == ".bash":
		return "🐚 ", "Shell Script"
	case ext == ".json" || ext == ".yaml" || ext == ".yml" || ext == ".toml":
		return "⚙️ ", "Config File"
	case isTextAttachment(att):
		return "📄 ", "Source Code"
	default:
		return "📎 ", "Attachment"
	}
}

func renderRightGraphicPane(m *tuiModel, att email.Attachment, width int, height int) string {
	t := m.theme.Theme()
	borderColor := t.Get(render.ColorBorder)
	if m.rightPaneFocus {
		borderColor = "#ffd700"
	}
	titleStyle := lipgloss.NewStyle().Bold(true).Foreground(lipgloss.Color(t.Get(render.ColorHighlightFg)))
	dimStyle := lipgloss.NewStyle().Foreground(lipgloss.Color(t.Get(render.ColorDate)))
	valStyle := lipgloss.NewStyle().Foreground(lipgloss.Color(t.Get(render.ColorFg)))

	icon, typeName := getPreviewIconAndType(att)

	focusHint := "[p: hide, Tab: focus]"
	if m.rightPaneFocus {
		focusHint = "[FOCUSED: j/k scroll, p/Esc hide, Tab return]"
		titleStyle = titleStyle.Foreground(lipgloss.Color("#ffd700"))
	}

	header := titleStyle.Render(icon+typeName+": ") + valStyle.Bold(true).Render(att.Filename) + " " + dimStyle.Render("("+formatFileSize(len(att.Data))+") "+focusHint)

	graphicH := max(4, height-2)
	graphicW := max(10, width-3)

	var content string
	switch {
	case email.IsICSAttachment(att):
		content = renderICSAttachmentPreview(m, att, graphicW)
	case isTextAttachment(att):
		content = renderCodeAttachmentPreview(att, graphicW)
	default:
		content = dimStyle.Render("(No preview available)")
	}

	if m.rightVp.Width != graphicW || m.rightVp.Height != graphicH || m.rightVpAttFilename != att.Filename {
		m.rightVp = viewport.New(graphicW, graphicH)
		m.rightVp.SetContent(content)
		m.rightVpAttFilename = att.Filename
	}

	paneBody := lipgloss.JoinVertical(lipgloss.Left,
		header,
		m.rightVp.View(),
	)

	vBorder := lipgloss.Border{
		Left: "│",
	}

	return lipgloss.NewStyle().
		Width(width - 1).
		Height(height).
		BorderStyle(vBorder).
		BorderLeft(true).
		BorderTop(false).
		BorderRight(false).
		BorderBottom(false).
		BorderForeground(lipgloss.Color(borderColor)).
		PaddingLeft(1).
		Render(paneBody)
}
