package gmail

import (
	"encoding/base64"
	"fmt"
	"github.com/sarielhp/mail_cli/report"
	"strings"
	"time"

	gmailapi "google.golang.org/api/gmail/v1"
)

// RunRESTTests verifies the program can create labels, insert and move
// messages, and clean up after itself.
//
// It does this against the real account: it creates a label, inserts a message
// into INBOX, moves it to that label, then deletes both. That is the point --
// a diagnostic that mocked the server would prove nothing about credentials or
// permissions -- but it makes this the one read path in the program that is not
// a read.
//
// It is therefore refused under --read-only and --dry-run. It used to run
// regardless: it builds its own service from a *Config rather than going
// through the client factory, so the ReadOnlyMailClient decorator that guards
// every other mutation never sees it, and `mail_cli --read-only doctor`
// created a label and inserted a message into a mailbox whose owner had just
// asked for nothing to change.
func RunRESTTests(rep report.Reporter, config *Config) error {
	if config != nil && (config.ReadOnly || config.DryRun) {
		flag := "--read-only"
		if config.DryRun {
			flag = "--dry-run"
		}
		rep.Warnf("doctor would create a label, insert a message into INBOX, move it, then delete both.\n")
		return fmt.Errorf("refusing to run the diagnostic under %s: it mutates the account by design", flag)
	}

	srv, err := GetGmailService(rep, config)
	if err != nil {
		return err
	}

	rep.Infof("Starting Gmail API Integration Tests...\n")

	// 1. Create a recursive label name
	timestamp := time.Now().UnixNano()
	testLabelName := fmt.Sprintf("test/temp/label-%d", timestamp)
	rep.Infof("Step 1: Creating recursive label %q...\n", testLabelName)

	createdLabel, err := srv.Users.Labels.Create("me", &gmailapi.Label{
		Name:                  testLabelName,
		LabelListVisibility:   "labelShow",
		MessageListVisibility: "show",
	}).Do()
	if err != nil {
		return fmt.Errorf("failed to create label %q: %w", testLabelName, err)
	}
	labelID := createdLabel.Id
	rep.Successf("Created label successfully (ID: %s).\n", labelID)

	// Defer cleanup of the label in case we fail later
	var labelCleanupErr error
	defer func() {
		rep.Infof("Step 5: Deleting recursive label %q...\n", testLabelName)
		labelCleanupErr = srv.Users.Labels.Delete("me", labelID).Do()
		if labelCleanupErr != nil {
			rep.Errorf("Failed to delete label %q: %v\n", testLabelName, labelCleanupErr)
		} else {
			rep.Successf("Deleted label %q successfully.\n", testLabelName)
		}
	}()

	// 2. Create a fake email inside INBOX
	rep.Infof("Step 2: Inserting a fake email into INBOX...\n")
	rawMessage := []byte("From: test-sender@example.com\r\n" +
		"To: " + config.Username + "\r\n" +
		"Subject: Integration Test Email\r\n" +
		"\r\n" +
		"This is a temporary test message generated by gmail.\r\n")

	msg := &gmailapi.Message{
		Raw:      base64.URLEncoding.EncodeToString(rawMessage),
		LabelIds: []string{"INBOX"},
	}

	createdMsg, err := srv.Users.Messages.Insert("me", msg).Do()
	if err != nil {
		return fmt.Errorf("failed to insert fake email: %w", err)
	}
	msgID := createdMsg.Id
	rep.Successf("Fake email inserted successfully (ID: %s).\n", msgID)

	// Defer cleanup of the message
	var msgCleanupErr error
	defer func() {
		if msgID != "" {
			rep.Infof("Step 4: Deleting fake email (ID: %s)...\n", msgID)
			msgCleanupErr = srv.Users.Messages.Delete("me", msgID).Do()
			if msgCleanupErr != nil {
				if !strings.Contains(msgCleanupErr.Error(), "404") {
					rep.Errorf("Failed to delete fake email: %v\n", msgCleanupErr)
				}
			} else {
				rep.Successf("Deleted fake email successfully.\n")
				msgID = ""
			}
		}
	}()

	// 3. Move the fake email to the created recursive label (remove from INBOX)
	rep.Infof("Step 3: Moving fake email to recursive label %q...\n", testLabelName)
	_, err = srv.Users.Messages.Modify("me", msgID, &gmailapi.ModifyMessageRequest{
		AddLabelIds:    []string{labelID},
		RemoveLabelIds: []string{"INBOX"},
	}).Do()
	if err != nil {
		return fmt.Errorf("failed to move message: %w", err)
	}
	rep.Successf("Moved email to %q successfully.\n", testLabelName)

	// Explicitly perform deletion step now to verify order
	rep.Infof("Step 4: Deleting fake email (ID: %s)...\n", msgID)
	err = srv.Users.Messages.Delete("me", msgID).Do()
	if err != nil {
		return fmt.Errorf("failed to delete fake email: %w", err)
	}
	msgID = "" // clear it so the deferred cleanup doesn't try to delete it again
	rep.Successf("Deleted fake email successfully.\n")

	return nil
}
